/**
 * Почему задача ждёт (1ж): люди её ролей в смене, но заняты; людей её ролей нет в смене; нет свободной техники; нет
 * свободного прибора; нет свободного места назначения; люди её ролей в смене есть, но ни один не допущен (Б3б); прибор
 * не откалиброван или у подрядчика, зона хранения не принимает паллет — поверка её датчика вышла или он у подрядчика (Б3в); люди её
 * ролей, которые были бы в смене, в отпуске, а заместителя в смене нет (Б4г). В потерях
 * суток есть ещё ожидание фуры: рампа занята (3а) — это ждёт не задача, а фура во дворе.
 */
export type WaitCause = 'people' | 'shift' | 'vehicle' | 'instrument' | 'place' | 'dock' | 'qual' | 'asset' | 'hours' | 'leave';

/** Место задачи: место паллеты, рампа с фурой или точка. */
export type Place = { kind: 'slot'; id: string } | { kind: 'truck'; id: string } | { kind: 'point'; x: number; z: number };

export interface Task {
  id: string;
  kind: TaskKind;
  /** кто может: любая из ролей */
  roles: Id[];
  /** какая техника годится: любая из; нет — пешком */
  veh?: Id[];
  /** паллета, которую везут или принимают */
  unit?: string;
  /** откуда (для перевозки) или где работа */
  from: Place;
  /** куда везти: вид зоны — место выбирается при назначении */
  toKind?: ZoneKind | 'storage';
  /** выбранное место назначения */
  to?: string;
  /** место назначения выбирать ближе к этой точке; нет — ближе к началу задачи */
  near?: { x: number; z: number };
  /** нужен свободный прибор одного из видов: он занят испытанием `test` с начала задачи */
  inst?: Id[];
  /** выбранный прибор */
  instrument?: string;
  /** кому задачу не давать: проверяет не тот, кто делал */
  not?: string[];
  /** о какой партии, каком испытании, какой серии или каком помещении задача */
  lot?: string;
  test?: string;
  batch?: string;
  room?: string;
  line?: string;
  /** заказ покупателя; ящики к отбору; паллета заказа, на которую их кладут; фура, в которую грузят */
  order?: string;
  cases?: string[];
  dest?: string;
  truck?: string;
  /** узел, который чинят или меняют; замена по плану, а не после отказа */
  part?: string;
  planned?: boolean;
  /** расследование и его шаг (часть 4) */
  inv?: string;
  step?: string;
  /** когда люди дошли и начали работу — событие `begin` (стадия с узлами под износом) */
  begin?: boolean;
  /** обучение (Б3б): чьё и какой редакции документа — id записи базы; изучает только он, знания проверяет не он */
  trainee?: string;
  doc?: Id;
  /** открытая задача: чего ждёт по последнему проходу раздатчика и с какого момента (1ж) */
  why?: WaitCause;
  since?: number;
  /** ждёт «нет допуска» (Б3б): код документа, которого не хватает */
  lack?: string;
  /** ждёт актив (Б3в): прибор или датчик зоны, который не пригоден; у приёмки работы подрядчика — чей актив */
  unfit?: string;
  asset?: string;
  /** оценка пары «поставщик — изготовитель» (Б3г): рассмотрение отчёта аудитора или документов — какой пары */
  pair?: string;
  /** оценка влияния отклонения (Б1г): какого */
  dev?: string;
  /** работа на месте, с */
  work: number;
  /**
   * у стадии (Б4а): норма по карте и наибольшая длительность с разбросом, с, — по ним раздатчик решает, помещается ли
   * она в смену и в сверхурочные; работа `work` — разыгранная, её завод не знает
   */
  norm?: [number, number];
  /** больше — раньше */
  prio: number;
  /** сколько людей нужно */
  count: number;
  created: number;
  state: 'open' | 'busy';
  people: string[];
  vehicle?: string;
  /** времена для отрисовки: начало, у груза, отъезд с грузом, у места, конец */
  times?: [number, number, number, number, number];
  /** версия: событие конца задачи с другой версией ничего не делает */
  v: number;
}

