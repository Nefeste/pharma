/**
 * Состояние помещения производства или упаковки для учёта его времени (Б1и; `iso-22400-2`, п. 5.1): работа — идёт
 * стадия серии или линия упаковывает задание; уборка и наладка — уборка помещения, мойка оборудования, переналадка
 * и очистка линии; серия ждёт — серия держит помещение, а работы нет; грязно — ждёт уборки; свободно — чисто и пусто.
 */
export type RoomPhase = 'work' | 'clean' | 'held' | 'dirty' | 'free';

/** Время помещения за сутки по состояниям, с; у полных суток сумма — 86 400 с. */
